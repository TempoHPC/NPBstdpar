
c---------------------------------------------------------------------
c---------------------------------------------------------------------

       subroutine  add

c---------------------------------------------------------------------
c---------------------------------------------------------------------

c---------------------------------------------------------------------
c addition of update to the vector u
c---------------------------------------------------------------------

       use sp_data
       implicit none

       integer i,j,k,m

       if (timeron) call timer_start(t_add)
       do concurrent (k = 1:nz2, j = 1:ny2, i = 1:nx2)
     >    local(m)
                do m = 1, 5
                   u(m,i,j,k) = u(m,i,j,k) + rhs(m,i,j,k)
                end do
       end do
       if (timeron) call timer_stop(t_add)

       return
       end

